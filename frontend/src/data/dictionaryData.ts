/**
 * Función de normalización para permitir búsquedas sin acentos ni diacríticos
 */
export function normalizeQuery(query: string): string {
  return query
    .toLowerCase()
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, '')
}

/**
 * Búsqueda inteligente en el diccionario local
 */
export function searchDictionary(query: string): DictionaryEntry[] {
  const qClean = query.trim()
  if (!qClean) return []

  const qNorm = normalizeQuery(qClean)

  return DICTIONARY_ENTRIES.filter((entry) => {
    // 1. Coincidencia directa con caracteres Hanzi
    if (entry.hanzi.includes(qClean)) return true

    // 2. Coincidencia con Pinyin normalizado (sin tonos ni espacios)
    const pinyinNorm = normalizeQuery(entry.pinyinNormalized)
    if (pinyinNorm.includes(qNorm)) return true

    // 3. Coincidencia con significado en español
    const translationNorm = normalizeQuery(entry.translationEs)
    if (translationNorm.includes(qNorm)) return true

    return false
  })
}
